const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));
const SUPPORTED = ['it', 'en', 'es'];

function detectLang() {
  try {
    const saved = localStorage.getItem('siro-lang');
    if (saved && SUPPORTED.includes(saved)) return saved;
  } catch (e) { /* ignore */ }
  const nav = (navigator.language || 'it').slice(0, 2).toLowerCase();
  return SUPPORTED.includes(nav) ? nav : 'it';
}

let currentLang = detectLang();

function applyLang(lang, persist = true) {
  if (!I18N[lang]) lang = 'it';
  currentLang = lang;
  const dict = I18N[lang];

  document.documentElement.lang = lang;
  if (dict.metaTitle) document.title = dict.metaTitle;
  const metaDesc = $('meta[name="description"]');
  if (metaDesc && dict.metaDesc) metaDesc.setAttribute('content', dict.metaDesc);

  $$('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] != null) el.textContent = dict[key];
  });
  $$('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] != null) el.innerHTML = dict[key];
  });

  $$('.lang-switch .tbtn').forEach(btn => {
    btn.setAttribute('aria-pressed', String(btn.getAttribute('data-lang') === lang));
  });

  if (persist) { try { localStorage.setItem('siro-lang', lang); } catch (e) {} }
  updateTime();
}

function setupLangSwitch() {
  $$('.lang-switch .tbtn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.getAttribute('data-lang')));
  });
}

function setupReveal() {
  const targets = $$('.section, .hero');
  if (!('IntersectionObserver' in window) || window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    targets.forEach(el => el.classList.add('in'));
    return;
  }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('in');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.08, rootMargin: '0px 0px -40px 0px' });
  targets.forEach(el => { el.classList.add('reveal'); observer.observe(el); });
}

function setupNavHighlight() {
  const navLinks = $$('.nav a');
  const sections = $$('main .section, .hero');
  const onScroll = () => {
    let current = '';
    sections.forEach(sec => { if (window.scrollY >= sec.offsetTop - 160) current = sec.id; });
    navLinks.forEach(a => a.classList.toggle('active', a.getAttribute('href') === '#' + current));
  };
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();
}

function setupMobileMenu() {
  const toggle = $('#navToggle');
  const menu = $('#navMenu');
  const nav = $('.site-nav');
  if (!toggle || !menu || !nav) return;

  const close = () => {
    nav.classList.remove('open');
    toggle.setAttribute('aria-expanded', 'false');
    toggle.setAttribute('aria-label', 'Apri menu');
  };

  toggle.addEventListener('click', () => {
    const open = nav.classList.toggle('open');
    toggle.setAttribute('aria-expanded', String(open));
    toggle.setAttribute('aria-label', open ? 'Chiudi menu' : 'Apri menu');
  });

  menu.addEventListener('click', e => { if (e.target.closest('a')) close(); });
  document.addEventListener('keydown', e => { if (e.key === 'Escape') close(); });
  window.addEventListener('resize', () => { if (window.innerWidth > 860) close(); });
}

function updateTime() {
  const el = $('#liveTime');
  if (!el) return;
  const now = new Date();
  const hh = String(now.getHours()).padStart(2, '0');
  const mm = String(now.getMinutes()).padStart(2, '0');
  const label = { it: 'Ora locale', en: 'Local time', es: 'Hora local' }[currentLang] || 'Ora locale';
  el.textContent = `${label} ${hh}:${mm}`;
}

